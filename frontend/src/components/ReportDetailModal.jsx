import React from 'react';
import { X } from 'lucide-react';
import { useToast } from '../context/ToastContext.jsx';
import { generateReportPDF } from '../lib/generateReportPDF';

const cn = (...classes) => classes.filter(Boolean).join(' ');

const TYPE_STYLES = {
 Financial: 'badge-financial',
 Risk: 'badge-risk',
 Compliance: 'badge-compliance',
 Custom: 'badge-custom',
};

const STATUS_STYLES = {
 Complete: 'badge-complete',
 Processing: 'badge-processing',
 Failed: 'badge-failed',
 Draft: 'badge-draft',
};

const getAccuracyColor = (val) => {
 if (val === null || val === undefined) return 'text-muted';
 if (val >= 80) return 'text-[#1a9e6e]';
 if (val >= 60) return 'text-[#c9870c]';
 return 'text-[#df1b41]';
};

export default function ReportDetailModal({ report, onClose }) {
 const { addToast } = useToast();
 const [isGeneratingPDF, setIsGeneratingPDF] = React.useState(false);
 
 const modelName = report.subtitle?.split('·')[0]?.trim() || report.model || 'AI Model';
 
 const getFeatures = (type) => {
 if (type === 'Financial') return [
 { label: 'Revenue Growth', value: 34.2 },
 { label: 'Debt Ratio', value: 28.7 },
 { label: 'Operating Margin', value: 18.4 },
 { label: 'Sector Benchmark', value: 11.3 },
 { label: 'Cash Flow', value: 7.4 }
 ];
 if (type === 'Risk') return [
 { label: 'Credit Exposure', value: 41.3 },
 { label: 'Market Volatility', value: 27.8 },
 { label: 'Liquidity Risk', value: 15.2 },
 { label: 'Counterparty Risk', value: 10.4 },
 { label: 'Operational Risk', value: 5.3 }
 ];
 return [
 { label: 'Regulatory Adherence', value: 38.1 },
 { label: 'Documentation', value: 24.6 },
 { label: 'Audit Trail', value: 19.3 },
 { label: 'Policy Violations', value: 12.2 },
 { label: 'Reporting Accuracy', value: 5.8 }
 ];
 };
 const features = getFeatures(report.type);
 
 const explanationText = report.description || `Analysis of ${report.dataSource || 'connected data source'} using ${modelName}. Key drivers identified include revenue trends, risk exposure, and compliance metrics. Accuracy achieved: ${report.accuracy ?? '—'}%.`;
 
 const rawData = JSON.stringify({
 company: "Acme Corp",
 period: "Q3 2024",
 revenue: 2450000,
 expenses: 1890000,
 debt_ratio: 0.34,
 sector: "Technology"
 }, null, 2);

 const getMarkdown = () => {
 let md = `# ${report.name}\n\n`;
 md += `**Type:** ${report.type} | **Status:** ${report.status} | **Created:** ${report.createdAt || report.created}\n\n`;
 md += `## Metadata\n| Field | Value |\n|-------|-------|\n`;
 md += `| Data Source | ${report.dataSource || '—'} |\n| Model | ${modelName} |\n| Accuracy | ${report.accuracy ? report.accuracy + (typeof report.accuracy === 'number' ? '%' : '') : '—'} |\n\n`;
 md += `## Explanation Output\n${explanationText}\n\n`;
 md += `## Feature Importance\n| Feature | Importance |\n|---------|-----------|\n`;
 features.forEach(f => { md += `| ${f.label} | ${f.value}% |\n`; });
 md += `\n## Raw Data\n\`\`\`json\n${rawData}\n\`\`\`\n\n---\n*Generated by SolvAI on ${new Date().toLocaleDateString()}*\n`;
 return md;
 };

 const handleCopyMD = () => {
 navigator.clipboard.writeText(getMarkdown());
 addToast('Report copied as Markdown', 'success');
 };

 const handleDownloadMD = () => {
 const blob = new Blob([getMarkdown()], { type: 'text/markdown' });
 const url = URL.createObjectURL(blob);
 const a = document.createElement('a');
 a.href = url;
 a.download = `solvai_${report.name.toLowerCase().replace(/\s+/g, '_').replace(/[^a-z0-9_]/g, '')}.md`;
 a.click();
 URL.revokeObjectURL(url);
 addToast('Markdown downloaded', 'success');
 };

 const handleDownloadPDF = async () => {
 setIsGeneratingPDF(true);
 addToast('Generating PDF report...', 'info');
 try {
 await generateReportPDF(report);
 addToast('PDF downloaded successfully', 'success');
 } catch (e) {
 addToast('Failed to generate PDF', 'error');
 } finally {
 setIsGeneratingPDF(false);
 }
 };

 // Handle escape key
 React.useEffect(() => {
 const handleEsc = (e) => {
 if (e.key === 'Escape') onClose();
 };
 window.addEventListener('keydown', handleEsc);
 return () => window.removeEventListener('keydown', handleEsc);
 }, [onClose]);

 return (
 <div className="fixed inset-0 bg-black/60 z-50 flex items-center justify-center p-4" onClick={onClose}>
 <div className="bg-card rounded-xl w-full max-w-[800px] max-h-[90vh] shadow-2xl overflow-y-auto border border-border" onClick={e => e.stopPropagation()}>
 <div className="flex justify-between items-start p-6 border-b border-border">
 <div>
 <h1 className="text-2xl font-bold text-primary mb-3">{report.name}</h1>
 <div className="flex items-center gap-2">
 <span className={cn(STATUS_STYLES[report.status] || STATUS_STYLES.Draft)}>{report.status}</span>
 <span className={cn(TYPE_STYLES[report.type] || TYPE_STYLES.Custom)}>{report.type}</span>
 </div>
 </div>
 <div className="flex items-center gap-2">
 <button onClick={handleCopyMD} className="px-3 py-1.5 text-sm font-medium border border-border rounded-md hover:bg-page transition-colors text-secondary">Copy MD</button>
 <button onClick={handleDownloadMD} className="px-3 py-1.5 text-sm font-medium border border-border rounded-md hover:bg-page transition-colors text-secondary">Download MD</button>
 <button 
 onClick={handleDownloadPDF} 
 disabled={isGeneratingPDF}
 className="px-3 py-1.5 text-sm font-medium bg-[#0570de] text-white rounded-md hover:bg-[#0462c7] transition-colors disabled:opacity-70 disabled:cursor-not-allowed"
 >
 {isGeneratingPDF ? 'Generating...' : 'Download PDF'}
 </button>
 <button onClick={onClose} className="ml-2 text-muted hover:text-primary transition-colors"><X className="w-5 h-5" /></button>
 </div>
 </div>
 
 <div className="p-6 space-y-8">
 {/* Section 1 */}
 <div className="grid grid-cols-2 gap-6">
 <div>
 <div className="text-sm text-muted mb-1">Created</div>
 <div className="text-sm font-medium text-primary">{report.createdAt || report.created || '—'}</div>
 </div>
 <div>
 <div className="text-sm text-muted mb-1">Data Source</div>
 <div className="text-sm font-medium text-primary">{report.dataSource || '—'}</div>
 </div>
 <div>
 <div className="text-sm text-muted mb-1">Model</div>
 <div className="text-sm font-medium text-primary">{modelName}</div>
 </div>
 <div>
 <div className="text-sm text-muted mb-1">Accuracy</div>
 <div className={cn('text-sm font-medium', getAccuracyColor(report.accuracy ? parseFloat(report.accuracy) : null))}>
 {report.accuracy !== null && report.accuracy !== undefined ? (typeof report.accuracy === 'number' ? `${report.accuracy}%` : report.accuracy) : '—'}
 </div>
 </div>
 </div>

 {/* Section 2 */}
 <div>
 <h3 className="text-sm font-semibold text-primary mb-3">Explanation Output</h3>
 <div className="bg-page rounded-md p-4 text-[14px] leading-[1.7] text-secondary">
 {explanationText}
 </div>
 </div>

 {/* Section 3 */}
 <div>
 <h3 className="text-sm font-semibold text-primary mb-4">Feature Importance</h3>
 <div className="space-y-4">
 {features.map((feat, i) => (
 <div key={i} className="flex items-center gap-4">
 <div className="w-40 text-sm font-medium text-secondary truncate">{feat.label}</div>
 <div className="flex-1 h-3 bg-page rounded-full overflow-hidden">
 <div className="h-full bg-[#0570de] rounded-full" style={{ width: `${feat.value}%` }}></div>
 </div>
 <div className="w-12 text-sm text-right text-muted">{feat.value}%</div>
 </div>
 ))}
 </div>
 </div>

 {/* Section 4 */}
 <div>
 <h3 className="text-sm font-semibold text-primary mb-3">Raw Data Preview</h3>
 <pre className="bg-[#111111] text-[#f5f5f5] p-4 rounded-md text-[13px] overflow-x-auto font-mono">
 {rawData}
 </pre>
 </div>
 </div>
 </div>
 </div>
 );
}
